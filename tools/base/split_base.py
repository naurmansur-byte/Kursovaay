def week(text: str, table: dict) -> int | str:
    t = ' ' + text.lower() + ' '
    hits = Counter({w: sum(t.count(k) for k in keys) for w, keys in table.items()})
    best = hits.most_common(1)[0]
    return best[0] if best[1] else '?'


def main() -> None:
    posts = json.loads((DIR / 'канал.json').read_text(encoding='utf-8'))
    facts = []
    for pid in sorted(posts, key=int):
        p = posts[pid]
        chem = int(pid) >= 541
        for raw in p['text'].split('\n'):
            raw = raw.strip()
            m = LINE.match(raw)
            if m and not chem:
                q, _, a = m.group(2).partition(':')
                facts.append(dict(subject='bio', n=int(m.group(1)), post=int(pid), q=q.strip(), a=a.strip(), week=week(m.group(2), BIO), picture=3051 <= int(m.group(1)) <= 3350))
            elif chem and ':' in raw and len(raw) > 8:
                q, _, a = raw.partition(':')
                facts.append(dict(subject='chem', n=None, post=int(pid), q=q.strip(), a=a.strip(), week=week(raw, CHEM), picture=False))
    (DIR / 'факты.json').write_text(json.dumps(facts, ensure_ascii=False, indent=1), encoding='utf-8')
    L = ['# База Био-Хим по неделям курса (автоматическая раскладка, проверить)\n', '| Неделя | Биология | из них рисунки | Химия |', '|---|---|---|---|']
    for w in list(range(1, 23)) + ['?']:
        b = [f for f in facts if f['subject'] == 'bio' and f['week'] == w]
        c = [f for f in facts if f['subject'] == 'chem' and f['week'] == w]
        L.append(f'| {w} | {len(b)} | {sum(f["picture"] for f in b)} | {len(c)} |')
    L.append(f'\nВсего: биология {sum(f["subject"] == "bio" for f in facts)}, химия {sum(f["subject"] == "chem" for f in facts)}.')
    (DIR / 'по неделям.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
