d = pathlib.Path(sys.argv[1])
texts = {}
for code in {**CHEM, **BIO}:
    f = d / f'{code}.txt'
    pages, page = {}, 0
    if f.exists():
        for line in f.read_text('utf-8').splitlines():
            m = re.match(r'=== PDF p\. (\d+) ===', line)
            if m:
                page = int(m.group(1)); continue
            pages.setdefault(page, []).append(line)
    texts[code] = {p: ' '.join(ls) for p, ls in pages.items()}

def look(spec, books):
    out = []
    for line in spec.splitlines():
        label, rx = line.split('|', 1)
        r = re.compile(rx, re.I)
        hits = []
        for code, name in books.items():
            ps = [p for p, t in texts[code].items() if r.search(t)]
            if ps:
                hits.append(f"{name} с. {', '.join(map(str, ps[:6]))}{' …' if len(ps) > 6 else ''}")
        out.append(f"| {label} | {'; '.join(hits) if hits else '**нет**'} |")
    return out

missing = [c for c in {**CHEM, **BIO} if not texts[c]]
res = ['# Сверка справочника фактов с учебниками перечня НЦТ (поиск по распознанному тексту)', '',
       f'Нет текста: {missing}', '', '## Химия', '', '| Факт | Найдено |', '|---|---|'] + look(C, CHEM) + \
      ['', '## Биология', '', '| Факт | Найдено |', '|---|---|'] + look(B, BIO)
pathlib.Path(sys.argv[2]).write_text('\n'.join(res), 'utf-8')
print('ok', missing)
